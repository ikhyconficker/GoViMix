const mkPlugin = (
  id: string,
  name: string,
  format: PluginFormat,
  vendor: string,
  type: PluginType,
  enabled = true,
  customParams?: Record<string, number>
): InsertPlugin => {
  const catalogMatch = PLUGIN_CATALOG.find((p) => p.name === name || p.type === type);
  return {
    id,
    name,
    format,
    vendor,
    type,
    enabled,
    params: { ...(catalogMatch?.defaultParams ?? {}), ...(customParams ?? {}) },
  };
};

