function makePeaks(seed: number, len = 48): number[] {
  const out: number[] = [];
  for (let i = 0; i < len; i++) {
    const v = Math.abs(Math.sin((i + 1) * seed * 0.7) * 0.6 + Math.cos((i + 3) * seed * 0.35) * 0.35);
    out.push(Math.min(0.95, Math.max(0.12, v)));
  }
  return out;
}

